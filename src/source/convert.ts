import { normalizeSource } from "./rule";

// —— 规则书源 → JS 脚本转换器 ——
// 把规则 JSON 机械翻译成 class 脚本（helper 复用规则引擎求值器，规则字符串原样可用）。
// 生成代码在 script 引擎下产出与规则引擎一致（test/convert.test.ts 验收）。
// 翻页：nextTocUrl → 源返回 {list,next} 引擎循环；{page} 模板 → 源内部展开（404/空页/无新章即停）。

const q = (s: any) => JSON.stringify(String(s ?? ""));
const hasPage = (s: any) => /\{\{?page\}?\}/.test(String(s ?? ""));
const ind = (s: string, n: number) => s.split("\n").map((l) => (l.trim() ? " ".repeat(n) + l : l)).join("\n");

// searchUrl "url,{json选项}" → fetchText 的 url 表达式 + opts 表达式（{{key}}/{{page}} 变 JS 插值）
function searchUrlExpr(tpl: string): string {
  let raw = String(tpl ?? "");
  let opts = "";
  const i = raw.indexOf(",{");
  if (i > -1) {
    try {
      const o = JSON.parse(raw.slice(i + 1));
      const parts: string[] = [];
      if (o.method) parts.push(`method: ${q(o.method)}`);
      if (o.body) parts.push(`body: ${q(o.body)}`);
      if (o.charset) parts.push(`charset: ${q(o.charset)}`);
      if (o.headers) {
        const h = typeof o.headers === "object" ? o.headers : JSON.parse(o.headers);
        parts.push(`headers: ${JSON.stringify(h)}`);
      }
      opts = parts.length ? `, { ${parts.join(", ")} }` : "";
      raw = raw.slice(0, i);
    } catch {
      // ponytail: 选项段非法就当纯 URL
    }
  }
  let js = q(raw);
  js = js.replace(/\{\{key\}\}/g, '" + encodeURIComponent(name) + "');
  js = js.replace(/\{\{page\}\}/g, '" + page + "');
  return `abs(${js})${opts}`;
}

// 章节映射表达式（列表项相对取值，规则缺省 = .text() / .attr('href')）
function chapterMap(listRule: any, nameRule: any, urlRule: any, resVar: string): string {
  const nr = String(nameRule || ".text()");
  const ur = String(urlRule || ".attr('href')");
  return (
    `ruleSel(ns, ${q(listRule)}).map((el) => ({\n` +
    `        title: ruleText([el], ${q(nr)}),\n` +
    `        url: abs(ruleText([el], ${q(ur)}), ${resVar}.url),\n` +
    `      })).filter((c) => c.title && c.url)`
  );
}

function headersMember(header: any): string {
  if (!header) return "";
  let h: any;
  try {
    h = typeof header === "object" ? header : JSON.parse(header);
  } catch {
    return "";
  }
  if (!h || typeof h !== "object" || !Object.keys(h).length) return "";
  return `  headers = ${JSON.stringify(h, null, 2).replace(/\n/g, "\n  ")};\n\n`;
}

function replaceMember(rr: any): string {
  if (!rr) return "";
  let rule = "";
  let rep = "";
  if (typeof rr === "object") {
    rule = String(rr.regex ?? "");
    rep = String(rr.replacement ?? "");
  } else {
    const parts = String(rr).split("##");
    rule = parts[0];
    rep = parts[1] ?? "";
  }
  if (!rule) return "";
  return `  replace = [{ regex: ${q(rule)}, replacement: ${q(rep)} }];\n\n`;
}

export function rulesToScript(src: any): string {
  const s = normalizeSource(src);
  const r = {
    search: s.ruleSearch ?? {},
    book: s.ruleBookInfo ?? {},
    toc: s.ruleToc ?? {},
    content: s.ruleContent ?? {},
  };
  const out: string[] = [];
  out.push(`// GENERATED by rules —— 本文件由规则书源「${s.bookSourceName ?? ""}」自动生成`);
  out.push(`// 编辑规则后保存会重新覆盖本代码；要手改逻辑请把源类型切换为 script`);
  out.push(`export default class Source {`);
  out.push(`  base = ${q(s.bookSourceUrl)};\n`);
  out.push(headersMember(s.header));
  out.push(replaceMember(r.content.replaceRegex));

  // search：searchUrl 缺省 = 该源不参与搜索（不生成方法）
  if (s.searchUrl) {
    out.push(`  async search(name, page = 1) {`);
    out.push(`    const res = await fetchText(${ind(searchUrlExpr(s.searchUrl), 4)});`);
    out.push(`    if (res.status >= 400) throw new Error("HTTP " + res.status);`);
    out.push(`    const ns = nodes(res.text);`);
    out.push(`    return ruleSel(ns, ${q(r.search.bookList)}).map((el) => ({`);
    out.push(`      title: ruleText([el], ${q(r.search.name || ".text()")}),`);
    out.push(`      author: ruleText([el], ${q(r.search.author || "")}),`);
    out.push(`      bookUrl: abs((ruleText([el], ${q(r.search.bookUrl || "")}).split(/\\s+/).pop() || ""), res.url),`);
    out.push(`      cover: abs((ruleText([el], ${q(r.search.coverUrl || "")}).split(/\\s+/)[0] || ""), res.url),`);
    out.push(`      desc: ruleText([el], ${q(r.search.intro || "")}),`);
    out.push(`      detailUrl: "", // 由 bookUrl 填充`);
    out.push(`    }))`);
    out.push(`      .map((b) => ({ ...b, detailUrl: b.bookUrl }))`);
    out.push(`      .filter((b) => b.title && b.detailUrl);`);
    out.push(`  }\n`);
  }

  // getDetail
  out.push(`  async getDetail(url) {`);
  out.push(`    const res = await fetchText(url);`);
  out.push(`    if (res.status >= 400) throw new Error("HTTP " + res.status);`);
  out.push(`    const ns = nodes(res.text);`);
  out.push(`    return {`);
  out.push(`      title: ruleText(ns, ${q(r.book.name || "")}),`);
  out.push(`      author: ruleText(ns, ${q(r.book.author || "")}),`);
  out.push(`      desc: ruleText(ns, ${q(r.book.intro || "")}),`);
  out.push(`      cover: abs((ruleText(ns, ${q(r.book.coverUrl || "")}).split(/\\s+/)[0] || ""), res.url),`);
  if (r.book.tocUrl) {
    const pageTpl = hasPage(r.book.tocUrl);
    const expr = pageTpl
      ? `ruleText(ns, ${q(r.book.tocUrl)}, res.url)` // {page} 模板原样返回（getChapters 内部展开）
      : `((ruleText(ns, ${q(r.book.tocUrl)}) || url).split(/\\s+/).pop() || url)`;
    out.push(`      tocUrl: abs(${expr}, res.url),`);
  }
  out.push(`    };`);
  out.push(`  }\n`);

  // getChapters：三种翻页形态
  const chMap = chapterMap(r.toc.chapterList, r.toc.chapterName, r.toc.chapterUrl, "res");
  const tplRule = [r.toc.nextTocUrl, r.book.tocUrl].find(hasPage);
  if (tplRule) {
    // {page} 模板：源内部循环展开，返回全量（引擎拿到的 next 为空，不再翻页）
    out.push(`  async getChapters(url) {`);
    out.push(`    const list = [];`);
    out.push(`    const seen = new Set();`);
    out.push(`    for (let page = 1; page <= 200; page++) {`);
    out.push(`      const res = await fetchText(String(url).replace(/\\{\\{?page\\}?\\}/g, String(page)).replace(/%7[Bb]page%7[Dd]/g, String(page)));`);
    out.push(`      if (res.status >= 400) break; // 到末页（4xx）即停`);
    out.push(`      const ns = nodes(res.text);`);
    out.push(`      const items = ${ind(chMap, 6)};`);
    out.push(`      let fresh = 0;`);
    out.push(`      for (const c of items) if (!seen.has(c.url)) { seen.add(c.url); list.push(c); fresh++; }`);
    out.push(`      if (!items.length || fresh === 0) break; // 空页或全是重复章节 → 结束`);
    out.push(`    }`);
    out.push(`    return { list };`);
    out.push(`  }\n`);
  } else if (r.toc.nextTocUrl) {
    // 下一页链接：返回 {list, next}，翻页循环在引擎（防环/去重/上限）
    out.push(`  async getChapters(url) {`);
    out.push(`    const res = await fetchText(url);`);
    out.push(`    if (res.status >= 400) throw new Error("HTTP " + res.status);`);
    out.push(`    const ns = nodes(res.text);`);
    out.push(`    const list = ${ind(chMap, 4)};`);
    out.push(`    const next = abs((ruleText(ns, ${q(r.toc.nextTocUrl)}).split(/\\s+/).pop() || ""), res.url);`);
    out.push(`    return { list, next: next || undefined };`);
    out.push(`  }\n`);
  } else {
    // 单页目录
    out.push(`  async getChapters(url) {`);
    out.push(`    const res = await fetchText(url);`);
    out.push(`    if (res.status >= 400) throw new Error("HTTP " + res.status);`);
    out.push(`    const ns = nodes(res.text);`);
    out.push(`    return { list: ${ind(chMap, 4)} };`);
    out.push(`  }\n`);
  }

  // getContent：{text, next} 交给引擎拼接（无 nextContentUrl 直接返回 string）
  out.push(`  async getContent(url) {`);
  out.push(`    const res = await fetchText(url);`);
  out.push(`    if (res.status >= 400) throw new Error("HTTP " + res.status);`);
  out.push(`    const ns = nodes(res.text);`);
  out.push(`    const text = ruleText(ns, ${q(r.content.content || "")});`);
  out.push(`    if (!text) throw new Error("正文规则未命中");`);
  if (r.content.nextContentUrl) {
    out.push(`    const next = abs((ruleText(ns, ${q(r.content.nextContentUrl)}).split(/\\s+/).pop() || ""), res.url);`);
    out.push(`    return next ? { text, next } : text;`);
  } else {
    out.push(`    return text;`);
  }
  out.push(`  }`);
  out.push(`}`);
  return out.join("\n");
}
